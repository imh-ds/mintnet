"""Hybrid raw-evidence runner for the frozen Stage 2i overlap-p=30
floor-search charter. See docs/stage2i_charter.md.

Simulates fresh data only for the four new, previously-untested sample
sizes (N=1600/1750/2000/2500). N=1500 is reused verbatim from Stage 2h's
raw evidence as the known bookend, mirroring Stage 1i's own
bookend-reuse pattern (mintnet.experiments.stage1i) exactly.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import subprocess
import sys
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from mintnet.experiments.stage1j_fit import fit_candidate_forms, select_form
from mintnet.experiments.stage2d import MOTIF_COMPONENTS, OVERLAP_PAIRS, Stage2dConfig, _score
from mintnet.experiments.stage2h import NOISE_COUNT, P, _sample_network
from mintnet.pipeline import compose_screen_then_prune
from mintnet.screening import compute_pairwise_screening_evidence, screen_uncorrected

BOOKEND_N = 1500


@dataclass(frozen=True)
class Stage2iConfig:
    sample_sizes: tuple[int, ...]
    strength: float
    screening_alpha: float
    replicates: int
    master_seed: int
    development_replicates: tuple[int, int]
    validation_replicates: tuple[int, int]
    minimum_indirect_prune_tpr: float
    maximum_true_edge_prune_fpr: float
    false_edge_rate_tolerance: float
    source_path: Path | None = None


def load_stage2i_config(path: Path) -> Stage2iConfig:
    """Load a Stage 2i configuration, retaining the path used to resolve it."""
    with path.open(encoding="utf-8") as stream:
        values = yaml.safe_load(stream)
    if not isinstance(values, dict):
        raise ValueError("Stage 2i configuration must be a mapping")

    return Stage2iConfig(
        sample_sizes=tuple(int(v) for v in values["sample_sizes"]),
        strength=float(values["strength"]),
        screening_alpha=float(values["screening_alpha"]),
        replicates=int(values["replicates"]),
        master_seed=int(values["master_seed"]),
        development_replicates=tuple(int(v) for v in values["development_replicates"]),
        validation_replicates=tuple(int(v) for v in values["validation_replicates"]),
        minimum_indirect_prune_tpr=float(values["minimum_indirect_prune_tpr"]),
        maximum_true_edge_prune_fpr=float(values["maximum_true_edge_prune_fpr"]),
        false_edge_rate_tolerance=float(values["false_edge_rate_tolerance"]),
        source_path=path.resolve(),
    )


def _condition_seed(config: Stage2iConfig, sample_index: int, replicate: int) -> int:
    # Keyed on each sample size's position in *this config's* sample_sizes
    # list -- only used to simulate the four new sample sizes; N=1500 is
    # never regenerated by this function, it is read from Stage 2h's evidence.
    sequence = np.random.SeedSequence([config.master_seed, sample_index, replicate])
    return int(sequence.generate_state(1)[0])


def _repository_root(config: Stage2iConfig) -> Path:
    if config.source_path is not None:
        return config.source_path.parent.parent
    return Path(__file__).resolve().parents[3]


def _git_commit(repository_root: Path) -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=repository_root, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def _resolved_config(config: Stage2iConfig) -> dict[str, object]:
    return {
        "sample_sizes": sorted(set(config.sample_sizes) | {BOOKEND_N}),
        "strength": config.strength,
        "noise_count": NOISE_COUNT,
        "screening_alpha": config.screening_alpha,
        "replicates": config.replicates,
        "master_seed": config.master_seed,
        "development_replicates": list(config.development_replicates),
        "validation_replicates": list(config.validation_replicates),
        "minimum_indirect_prune_tpr": config.minimum_indirect_prune_tpr,
        "maximum_true_edge_prune_fpr": config.maximum_true_edge_prune_fpr,
        "false_edge_rate_tolerance": config.false_edge_rate_tolerance,
    }


def _write_evidence(
    config: Stage2iConfig,
    output_dir: Path,
    raw: pd.DataFrame,
    bookend_raw_evidence_path: Path,
    runtime_seconds: float,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    raw.to_csv(output_dir / "raw_metrics.csv", index=False)
    with (output_dir / "resolved_config.yaml").open("w", encoding="utf-8") as stream:
        yaml.safe_dump(_resolved_config(config), stream, sort_keys=True)

    repository_root = _repository_root(config)
    charter = repository_root / "docs/stage2i_charter.md"
    charter_hash = hashlib.sha256(charter.read_bytes()).hexdigest() if charter.is_file() else None
    metadata = {
        "charter_sha256": charter_hash,
        "bookend_raw_evidence_path": str(bookend_raw_evidence_path),
        "bookend_raw_evidence_sha256": hashlib.sha256(bookend_raw_evidence_path.read_bytes()).hexdigest(),
        "git_commit": _git_commit(repository_root),
        "python": sys.version,
        "platform": platform.platform(),
        "recorded_at_utc": datetime.now(UTC).isoformat(),
        "runtime_seconds": runtime_seconds,
    }
    (output_dir / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")


def _simulate(config: Stage2iConfig) -> pd.DataFrame:
    """Simulate raw evidence for exactly the sample sizes in config.sample_sizes."""
    p = P
    selected_form = select_form(fit_candidate_forms())

    rows: list[dict[str, object]] = []
    for sample_index, n in enumerate(config.sample_sizes):
        dpi_alpha = selected_form.predict(float(n))
        for replicate in range(config.replicates):
            seed = _condition_seed(config, sample_index, replicate)
            started = time.perf_counter()
            row_status, row_error = "ok", ""
            metrics: dict[str, float] = {
                "chain_indirect_tpr": np.nan,
                "fork_indirect_tpr": np.nan,
                "overlap_indirect_tpr": np.nan,
                "true_edge_prune_fpr": np.nan,
                "screening_false_edge_rate": np.nan,
                "final_false_edge_rate": np.nan,
            }
            chain_is_triad = fork_is_triad = overlap_is_validated = overlap_clean_clique = np.nan
            try:
                data = _sample_network(n, config.strength, np.random.default_rng(seed))
                evidence = compute_pairwise_screening_evidence(data)
                screened = screen_uncorrected(evidence, config.screening_alpha)
                final, shapes = compose_screen_then_prune(data, screened, dpi_alpha)
                metrics = _score(screened, final, p)

                def _validated(component: frozenset[int]) -> float:
                    shape = shapes.get(component)
                    return float(shape["is_validated_shape"]) if shape is not None else 0.0

                chain_is_triad = _validated(MOTIF_COMPONENTS["chain"])
                fork_is_triad = _validated(MOTIF_COMPONENTS["fork"])
                overlap_is_validated = _validated(MOTIF_COMPONENTS["overlap"])
                overlap_clean_clique = float(all(screened[i, j] for i, j in OVERLAP_PAIRS))
            except Exception as exc:  # raw evidence must retain pipeline failures
                row_status, row_error = "error", f"{type(exc).__name__}: {exc}"

            rows.append(
                {
                    "n": n,
                    "replicate": replicate,
                    "seed": seed,
                    "dpi_alpha": dpi_alpha,
                    **metrics,
                    "chain_is_triad": chain_is_triad,
                    "fork_is_triad": fork_is_triad,
                    "overlap_is_validated": overlap_is_validated,
                    "overlap_clean_clique": overlap_clean_clique,
                    "elapsed_seconds": time.perf_counter() - started,
                    "status": row_status,
                    "error": row_error,
                }
            )
    return pd.DataFrame(rows)


def run_stage2i(config: Stage2iConfig, bookend_raw_evidence_path: Path, output_dir: Path) -> pd.DataFrame:
    """Simulate the four new sample sizes and merge in Stage 2h's N=1500 bookend."""
    run_started = time.perf_counter()
    new_raw = _simulate(config)

    bookend_raw = pd.read_csv(bookend_raw_evidence_path)
    bookend_raw = bookend_raw.loc[bookend_raw["n"] == BOOKEND_N].copy()

    raw = pd.concat([new_raw, bookend_raw], ignore_index=True)
    _write_evidence(config, output_dir, raw, bookend_raw_evidence_path, time.perf_counter() - run_started)
    from mintnet.experiments.stage2i_reporting import write_stage2i_report

    report_config = Stage2dConfig(
        sample_sizes=tuple(sorted(set(config.sample_sizes) | {BOOKEND_N})),
        strength=config.strength,
        screening_alpha=config.screening_alpha,
        replicates=config.replicates,
        master_seed=config.master_seed,
        development_replicates=config.development_replicates,
        validation_replicates=config.validation_replicates,
        minimum_indirect_prune_tpr=config.minimum_indirect_prune_tpr,
        maximum_true_edge_prune_fpr=config.maximum_true_edge_prune_fpr,
        false_edge_rate_tolerance=config.false_edge_rate_tolerance,
    )
    write_stage2i_report(raw, report_config, output_dir)
    return raw


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, type=Path)
    parser.add_argument("--bookend-raw-evidence", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    arguments = parser.parse_args()
    run_stage2i(
        load_stage2i_config(arguments.config), arguments.bookend_raw_evidence, arguments.output
    )


if __name__ == "__main__":
    main()
